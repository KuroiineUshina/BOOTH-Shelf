const TRANSLATIONS = Object.freeze({
  en: Object.freeze(EN),
  ja: Object.freeze(JA),
});

let activeLocale = "ko";
let capturedTextNodes;
let capturedAttributes;

function interpolate(template, values) {
  return String(template).replace(/\{([A-Za-z0-9_]+)\}/g, (match, key) => (
    Object.hasOwn(values, key) ? String(values[key]) : match
  ));
}

export function normalizeLocale(value, fallback = "ko") {
  const normalized = String(value || "").toLocaleLowerCase("en-US");
  if (normalized.startsWith("ja")) return "ja";
  if (normalized.startsWith("en")) return "en";
  if (normalized.startsWith("ko")) return "ko";
  return SUPPORTED_LOCALES.includes(fallback) ? fallback : "ko";
}

export function resolveLocale(preference, browserLocale = "") {
  return preference === "auto"
    ? normalizeLocale(browserLocale, "ko")
    : normalizeLocale(preference, "ko");
}

export function setLocale(locale) {
  activeLocale = normalizeLocale(locale);
  return activeLocale;
}

export function getLocale() {
  return activeLocale;
}

export function getLocaleTag() {
  return LOCALE_TAGS[activeLocale];
}

export function t(key, values = {}) {
  const translated = TRANSLATIONS[activeLocale]?.[key] ?? key;
  return interpolate(translated, values);
}

export function formatLocalizedNumber(value, options) {
  return Number(value || 0).toLocaleString(getLocaleTag(), options);
}

export function formatLocalizedDate(value, options) {
  return new Intl.DateTimeFormat(getLocaleTag(), options).format(value);
}

function hasTranslation(key) {
  return Boolean(EN[key] || JA[key]);
}

function captureStaticTranslations(root) {
  capturedTextNodes = [];
  capturedAttributes = [];

  const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT);
  let node = walker.nextNode();
  while (node) {
    const parent = node.parentElement;
    if (parent && !["SCRIPT", "STYLE"].includes(parent.tagName)) {
      const match = node.data.match(/^(\s*)(.*?)(\s*)$/s);
      const key = match?.[2] ?? "";
      if (key && hasTranslation(key)) {
        capturedTextNodes.push({
          node,
          key,
          prefix: match[1],
          suffix: match[3],
        });
      }
    }
    node = walker.nextNode();
  }

  for (const element of root.querySelectorAll("[aria-label], [title], [placeholder]")) {
    for (const attribute of ["aria-label", "title", "placeholder"]) {
      const key = element.getAttribute(attribute);
      if (key && hasTranslation(key)) capturedAttributes.push({ element, attribute, key });
    }
  }
}

export function applyDocumentTranslations(root = document.body) {
  if (!capturedTextNodes || !capturedAttributes) captureStaticTranslations(root);

  for (const { node, key, prefix, suffix } of capturedTextNodes) {
    if (node.isConnected) node.data = `${prefix}${t(key)}${suffix}`;
  }
  for (const { element, attribute, key } of capturedAttributes) {
    if (element.isConnected) element.setAttribute(attribute, t(key));
  }
  document.documentElement.lang = activeLocale;
}
